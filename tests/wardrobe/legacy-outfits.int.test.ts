import { afterAll, expect, it } from 'vitest';
import { asOwnerId } from '@/platform/kernel';
import { createPrismaOutfitStore } from '@/modules/wardrobe/infrastructure/prisma-outfit-store';
import { newId } from '@/platform/http/ids';
import { closeAll, db, wardrobeHarness } from './harness';
afterAll(closeAll);
it('keeps the legacy outfit adapter compatible with the current schema and immutable wear snapshots', async () => {
  const h = wardrobeHarness();
  const a = await h.signedIn();
  const b = await h.signedIn();
  const g = await h.api.createGarment(a.cookie, h.shirt({ nickname: 'Original' }));
  const id = String(g.body!.id);
  const store = createPrismaOutfitStore(db);
  const owner = asOwnerId(a.userId);
  const now = new Date('2026-10-29T08:30:00Z');
  const draft = await store.create(owner, { name: 'Legacy draft', garmentIds: [id] }, now, newId());
  expect(draft).toMatchObject({ name: 'Legacy draft', status: 'DRAFT' });
  expect(await store.get(asOwnerId(b.userId), draft!.id)).toBeNull();
  const planned = await store.update(owner, draft!.id, 1, { status: 'PLANNED', plannedFor: now, occasion: 'Work' }, now);
  expect(planned!.plannedFor).toBe(now.toISOString());
  expect(await store.list(owner, { from: new Date('2026-10-29'), to: new Date('2026-10-30') })).toHaveLength(1);
  const confirmed = await store.confirmWorn(owner, draft!.id, now, newId(), newId);
  expect(confirmed.kind).toBe('OK');
  expect((await store.wearsOf(owner, id))[0]?.wornAt).toBe(now.toISOString());
  expect((await h.api.getGarment(a.cookie, id)).body!.status).toBe('AVAILABLE');
  const records = await db.wearRecord.findMany({ where: { ownerId: owner }, include: { items: true } });
  expect(records[0]!.items[0]).toMatchObject({ nickname: 'Original', primaryColorCode: 'BLUE' });
  expect(await store.confirmWorn(owner, draft!.id, now, newId(), newId)).toMatchObject({ kind: 'ALREADY_WORN' });
});
