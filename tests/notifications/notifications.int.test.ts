import { randomUUID } from 'node:crypto';
import { afterAll, expect, it } from 'vitest';
import { createNotificationsHttp, createNotificationJob } from '@/modules/notifications';
import { createAnalyticsHttp } from '@/modules/analytics';
import { asOwnerId } from '@/platform/kernel';
import { createRateLimiter } from '@/platform/rate-limit';
import { wardrobeHarness, db, closeAll } from '../wardrobe/harness';
import { redis } from '../identity/harness';
afterAll(closeAll);
it('requires opt-in, deduplicates retries, isolates users, preserves dismissals, hides changed sources and expires rows', async () => {
    const h = wardrobeHarness(), a = await h.signedIn(), b = await h.signedIn();
    const api = createNotificationsHttp({ db, clock: h.clock, withSession: h.withSession, limiter: createRateLimiter(redis, randomUUID()) });
    const call = (fn: (r: Request) => Promise<Response>, cookie = a.cookie, method = 'GET', body?: unknown) => h.send(fn, h.request('/notifications', { cookie, method, body }));
    const now = h.clock.now(), startsAt = new Date(now.getTime() + 30 * 60000), outfitId = randomUUID();
    await db.outfit.create({ data: { id: outfitId, ownerId: a.userId, status: 'PLANNED', startsAt, createdAt: now, updatedAt: now } });
    expect((await call(api.refresh, a.cookie, 'POST')).body).toEqual({ created: 0 });
    expect((await call(api.setPreferences, a.cookie, 'PUT', { enabled: true, minutesBefore: 60 })).status).toBe(200);
    expect((await call(api.refresh, a.cookie, 'POST')).body).toEqual({ created: 1 });
    expect((await call(api.refresh, a.cookie, 'POST')).body).toEqual({ created: 0 });
    const n = (await call(api.list)).body!.items as {
        id: string;
    }[];
    expect(n).toHaveLength(1);
    const id = n[0]!.id;
    expect((await call(r => api.read(r, id), b.cookie, 'PUT')).status).toBe(404);
    expect((await call(api.list, b.cookie)).body!.items).toEqual([]);
    expect((await call(r => api.dismiss(r, id), a.cookie, 'DELETE')).status).toBe(204);
    await call(api.refresh, a.cookie, 'POST');
    expect((await call(api.list)).body!.items).toEqual([]);
    await db.outfit.update({ where: { id: outfitId }, data: { startsAt: new Date(now.getTime() + 45 * 60000) } });
    await call(api.refresh, a.cookie, 'POST');
    expect(((await call(api.list)).body!.items as unknown[])).toHaveLength(1);
    await db.outfit.update({ where: { id: outfitId }, data: { status: 'CANCELLED' } });
    expect((await call(api.list)).body!.items).toEqual([]);
    await db.notification.updateMany({ where: { ownerId: a.userId }, data: { expiresAt: new Date(now.getTime() - 1) } });
    await createNotificationJob(db)(now);
    expect(await db.notification.count({ where: { ownerId: a.userId } })).toBe(0);
});
it('analytics excludes foreign, trashed and invalidated wears and keeps costs in their own currency', async () => {
    const h = wardrobeHarness(), a = await h.signedIn(), b = await h.signedIn();
    const own = await h.api.createGarment(a.cookie, h.shirt({ purchasePrice: 100, purchaseCurrency: 'EUR' }));
    await h.api.createGarment(b.cookie, h.shirt());
    const trash = await h.api.createGarment(a.cookie, h.shirt());
    await h.api.deleteGarment(a.cookie, String(trash.body!.id));
    const now = h.clock.now(), outfitId = randomUUID(), wearId = randomUUID();
    await db.outfit.create({ data: { id: outfitId, ownerId: a.userId, status: 'WORN', createdAt: now, updatedAt: now } });
    await db.wearRecord.create({ data: { id: wearId, ownerId: a.userId, outfitId, status: 'ACTIVE', activeSlot: 1, confirmedAt: new Date(now.getTime() - 1000), localDate: new Date(now.toISOString().slice(0, 10)), localTime: '12:00', timezone: 'UTC', createdAt: now, items: { create: { id: randomUUID(), garmentId: String(own.body!.id), role: 'TOP', position: 0, categoryCode: 'TOPS', primaryColorCode: 'BLUE', extraColorCodes: [] } } } });
    const api = createAnalyticsHttp({ db, clock: h.clock, withSession: h.withSession, limiter: createRateLimiter(redis, randomUUID()) });
    const call = () => h.send(api, h.request('/analytics', { cookie: a.cookie }));
    const s = (await call()).body!;
    expect(s.eligible).toBe(1);
    expect(s.used).toBe(1);
    expect(s.spending).toEqual([{ currency: 'EUR', amount: 100 }]);
    await db.wearRecord.update({ where: { id: wearId }, data: { status: 'INVALIDATED', activeSlot: null } });
    expect((await call()).body!.used).toBe(0);
    expect((await h.send(api, h.request('/analytics?from=2099-01-01', { cookie: a.cookie }))).status).toBe(400);
    expect(asOwnerId(a.userId)).toBe(a.userId);
});
