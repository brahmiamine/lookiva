import { afterAll, it, expect } from 'vitest';
import { randomUUID } from 'node:crypto';
import { createPlanningHttp } from '@/modules/planning';
import { createGarmentGateway } from '@/modules/wardrobe';
import { redis } from '../identity/harness';
import { wardrobeHarness, db, closeAll } from '../wardrobe/harness';
afterAll(closeAll);
it('persists owner-scoped events, replays creates, guards versions and generates virtual dates', async () => {
    const h = wardrobeHarness(), a = await h.signedIn(), b = await h.signedIn();
    const p = createPlanningHttp({ db, redis, clock: h.clock, withSession: h.withSession, garments: createGarmentGateway(db, h.clock), rateLimitPrefix: randomUUID() });
    const send = (fn: (r: Request) => Promise<Response>, cookie: string, method = 'GET', body?: unknown, headers = {}) => h.send(fn, h.request('/events', { cookie, method, body, headers }));
    const body = { title: 'Sport', date: '2026-10-25', timezone: 'Europe/Paris', type: 'SPORT', recurrence: { frequency: 'WEEKLY', interval: 1 }, checklist: [{ id: randomUUID(), text: 'Gourde', done: false }] };
    const headers = { 'idempotency-key': randomUUID() };
    const created = await send(p.events.create, a.cookie, 'POST', body, headers);
    expect(created.status).toBe(201);
    expect((await send(p.events.create, a.cookie, 'POST', body, headers)).body).toEqual(created.body);
    const id = String(created.body!.id);
    expect((await send(r => p.events.get(r, id), b.cookie)).status).toBe(404);
    expect((await send(r => p.events.update(r, id), a.cookie, 'PUT', body)).status).toBe(428);
    const updated = await send(r => p.events.update(r, id), a.cookie, 'PUT', { ...body, title: 'Sport modifié' }, { 'if-match': 'W/"v1"' });
    expect(updated.status).toBe(200);
    expect((await send(r => p.events.remove(r, id), a.cookie, 'DELETE', undefined, { 'if-match': 'W/"v1"' })).status).toBe(409);
    const occ = await h.send(r => p.occurrences(r, id), h.request(`/events/${id}/occurrences?from=2026-10-25&to=2026-11-08`, { cookie: a.cookie }));
    expect(occ.status).toBe(200);
    expect((occ.body!.items as unknown[])).toHaveLength(3);
    expect(await db.wearRecord.count({ where: { ownerId: a.userId } })).toBe(0);
    expect((await send(r => p.events.remove(r, id), a.cookie, 'DELETE', undefined, { 'if-match': 'W/"v2"' })).status).toBe(204);
});
it('prepares multi-city trips without changing garment state and rejects foreign selections', async () => {
    const h = wardrobeHarness(), a = await h.signedIn(), b = await h.signedIn(), g = await h.api.createGarment(a.cookie, h.shirt());
    const p = createPlanningHttp({ db, redis, clock: h.clock, withSession: h.withSession, garments: createGarmentGateway(db, h.clock), rateLimitPrefix: randomUUID() });
    const body = { title: 'Voyage', from: '2026-11-01', to: '2026-11-10', garmentIds: [String(g.body!.id)], stages: [{ city: 'Paris', timezone: 'Europe/Paris', from: '2026-11-01', to: '2026-11-04' }, { city: 'Tokyo', timezone: 'Asia/Tokyo', from: '2026-11-05', to: '2026-11-10' }] };
    const tripKey = randomUUID();
    const req = (cookie: string) => h.request('/trips', { cookie, method: 'POST', body, headers: { 'idempotency-key': tripKey } });
    expect((await h.send(p.trips.create, req(b.cookie))).status).toBe(404);
    const r = await h.send(p.trips.create, req(a.cookie));
    expect(r.status).toBe(201);
    const packed = await h.send(req => p.packing(req, String(r.body!.id)), h.request('/trips/packing', { cookie: a.cookie }));
    expect(packed.body).toMatchObject({ pieces: 1, weightKnown: false, warnings: [] });
    expect((await h.api.getGarment(a.cookie, String(g.body!.id))).body!.status).toBe('AVAILABLE');
    await h.api.deleteGarment(a.cookie, String(g.body!.id));
    expect((await h.send(p.trips.create, req(a.cookie))).status).toBe(201);
    const changed = await h.send(req => p.trips.update(req, String(r.body!.id)), h.request('/trips', { cookie: a.cookie, method: 'PUT', body: { ...body, checklist: [{ id: randomUUID(), text: 'Passport', done: true }] }, headers: { 'if-match': 'W/"v1"' } }));
    expect(changed.status).toBe(200);
    const missing = await h.send(req => p.packing(req, String(r.body!.id)), h.request('/trips/packing', { cookie: a.cookie }));
    expect(missing.body).toMatchObject({ warnings: [{ id: String(g.body!.id), code: 'MISSING' }] });
});
